export async function GET(req: NextRequest): Promise<NextResponse> {
  const tenantId = req.headers.get("x-tenant-id") ?? "";
  if (!tenantId) return NextResponse.json({ error: "x-tenant-id required" }, { status: 400 });

  try {
    const supabase = await createTenantSupabaseClient(tenantId);

    // Seed if needed
    const { data: existing } = await supabase
      .from("natural_diamond_prices")
      .select("id")
      .eq("tenant_id", tenantId)
      .limit(1);

    if (!existing || existing.length === 0) {
      const now = new Date().toISOString();
      const seedRows = buildSeedRows(tenantId, now);
      for (let i = 0; i < seedRows.length; i += 200) {
        await supabase.from("natural_diamond_prices").upsert(
          seedRows.slice(i, i + 200),
          { onConflict: "tenant_id,shape,size_from,size_to,colour_group,clarity" }
        );
      }
    }

    const [pricesRes, tenantRes, marginRes] = await Promise.all([
      supabase
        .from("natural_diamond_prices")
        .select("shape,size_from,size_to,colour_group,clarity,price_per_ct")
        .eq("tenant_id", tenantId)
        .order("shape").order("size_from").order("colour_group").order("clarity"),
      supabase
        .from("tenants")
        .select("stone_currency_rate")
        .eq("id", tenantId)
        .maybeSingle(),
      supabase
        .from("pricing_margin_config")
        .select("margin_percent")
        .eq("tenant_id", tenantId)
        .eq("category", "stone_natural")
        .maybeSingle(),
    ]);

    return NextResponse.json({
      prices:          pricesRes.data   ?? [],
      currency_rate:   tenantRes.data?.stone_currency_rate ?? 1.538,
      natural_margin:  marginRes.data?.margin_percent ?? 30,
    });
  } catch (err) {
    return NextResponse.json({ error: String(err) }, { status: 500 });
  }
}

// ── POST ───────────────────────────────────────────────────────────────────────

export async function POST(req: NextRequest): Promise<NextResponse> {
  const tenantId = req.headers.get("x-tenant-id") ?? "";
  if (!tenantId) return NextResponse.json({ error: "x-tenant-id required" }, { status: 400 });

  try {
    const body = await req.json() as {
      prices?:          Array<{ shape: string; size_from: number; size_to: number; colour_group: string; clarity: string; price_per_ct: number }>;
      currency_rate?:   number;
      natural_margin?:  number;
    };

    const supabase = await createTenantSupabaseClient(tenantId);
    const now = new Date().toISOString();

    if (Array.isArray(body.prices) && body.prices.length > 0) {
      const rows = body.prices.map(p => ({
        tenant_id:    tenantId,
        shape:        p.shape,
        size_from:    p.size_from,
        size_to:      p.size_to,
        colour_group: p.colour_group,
        clarity:      p.clarity,
        price_per_ct: p.price_per_ct,
        updated_at:   now,
      }));
      for (let i = 0; i < rows.length; i += 200) {
        await supabase.from("natural_diamond_prices").upsert(
          rows.slice(i, i + 200),
          { onConflict: "tenant_id,shape,size_from,size_to,colour_group,clarity" }
        );
      }
    }

    if (body.currency_rate !== undefined) {
      await supabase.from("tenants")
        .update({ stone_currency_rate: body.currency_rate })
        .eq("id", tenantId);
    }

    if (body.natural_margin !== undefined) {
      await supabase.from("pricing_margin_config").upsert(
        { tenant_id: tenantId, category: "stone_natural", margin_percent: body.natural_margin, updated_at: now },
        { onConflict: "tenant_id,category" }
      );
    }

    return NextResponse.json({ ok: true });
  } catch (err) {
    return NextResponse.json({ error: String(err) }, { status: 500 });
  }
}
